"""The WP-088 result table: results.json (machine-readable) and results.md.

AGENT-CONTRACT (docs/qualification.md, evidence/WP-088.md): one row per
(configuration, operation) with status passed | failed | unqualified and a
reason for every status other than passed. The Markdown summary is what the
evidence file embeds; --evidence copies both next to it.
"""
import json
import os
import platform
import subprocess
from collections import Counter, OrderedDict

STATUSES = ("passed", "failed", "unqualified")


def host_description():
    def first_line(command):
        try:
            done = subprocess.run(command, capture_output=True, text=True, timeout=10)
            return (done.stdout.strip() or done.stderr.strip()).splitlines()[0]
        except (OSError, IndexError, subprocess.TimeoutExpired):
            return "?"
    renderer = "?"
    try:
        with open("/sys/class/drm/card0/device/vendor") as vendor:
            renderer = {"0x1002": "AMD", "0x10de": "NVIDIA", "0x8086": "Intel"}.get(vendor.read().strip(), "?")
    except OSError:
        pass
    return OrderedDict([("kernel", platform.release()), ("distribution", first_line(["uname", "-o"])),
                        ("weston", first_line(["weston", "--version"])),
                        ("xwayland", first_line(["Xwayland", "-version"])), ("gpuVendor", renderer)])


class Results:
    def __init__(self, run_id, out_dir, arguments):
        self.run_id = run_id
        self.out_dir = out_dir
        self.arguments = arguments
        self.rows = []
        self.builds = []

    def add(self, qt, variant, configuration, operation, outcome):
        assert outcome["status"] in STATUSES, outcome
        if outcome["status"] != "passed":
            assert outcome["reason"], (configuration, operation, outcome)
        self.rows.append(OrderedDict([("qt", qt), ("variant", variant), ("configuration", configuration),
                                      ("operation", operation), ("status", outcome["status"]),
                                      ("reason", outcome["reason"]), ("evidence", outcome["evidence"]),
                                      ("log", outcome.get("log", ""))]))

    def add_build(self, variant, status, reason=""):
        self.builds.append(OrderedDict([("qt", variant.qt), ("variant", variant.variant),
                                        ("buildDir", variant.name), ("features", variant.features),
                                        ("status", status), ("reason", reason)]))

    def document(self):
        counts = Counter(row["status"] for row in self.rows)
        return OrderedDict([("schema", "qindatk-qualification/1"), ("runId", self.run_id),
                            ("arguments", self.arguments), ("host", host_description()),
                            ("summary", {s: counts.get(s, 0) for s in STATUSES}),
                            ("builds", self.builds), ("results", self.rows)])

    def markdown(self):
        document = self.document()
        lines = ["<!-- SPDX-License-Identifier: LGPL-3.0-or-later -->",
                 "<!-- Generated by tools/qualify/qualify.py; do not edit by hand. -->",
                 "# WP-088 qualification results (%s)" % self.run_id, "",
                 "Command: `python3 tools/qualify/qualify.py %s`" % " ".join(self.arguments), "",
                 "Host: " + ", ".join("%s %s" % (k, v) for k, v in document["host"].items()), "",
                 "Totals: " + ", ".join("%d %s" % (document["summary"][s], s) for s in STATUSES), "",
                 "## Builds", "", "| Qt | Variant | Resolved optional engines | Build |", "| --- | --- | --- | --- |"]
        for build in self.builds:
            features = build["features"]
            on = ", ".join(k for k, v in features.items() if v is True) or "none"
            status = build["status"] + (": " + build["reason"] if build["reason"] else "")
            lines.append("| %s (%s) | %s | %s | %s |" % (build["qt"], features.get("qtVersion", "?"),
                                                         build["variant"], on, status))
        matrix = [r for r in self.rows if r["configuration"] not in ("installed", "build")]
        configurations = list(OrderedDict.fromkeys((r["qt"], r["variant"], r["configuration"]) for r in matrix))
        operations = list(OrderedDict.fromkeys(r["operation"] for r in matrix))
        if matrix:
            lines += ["", "## Configuration × operation", "",
                      "P passed, F failed, U unqualified; reasons follow the table.", "",
                      "| Qt / variant / configuration | " + " | ".join(operations) + " |",
                      "| --- |" + " --- |" * len(operations)]
            cell = {(r["qt"], r["variant"], r["configuration"], r["operation"]): r for r in matrix}
            for key in configurations:
                marks = []
                for operation in operations:
                    row = cell.get(key + (operation,))
                    marks.append({"passed": "P", "failed": "**F**", "unqualified": "U"}[row["status"]] if row else "–")
                lines.append("| %s / %s / %s | " % key + " | ".join(marks) + " |")
        installed = [r for r in self.rows if r["configuration"] in ("installed", "build")]
        if installed:
            lines += ["", "## Install, relocation and optional engines", "",
                      "| Qt / variant | Check | Status | Detail |", "| --- | --- | --- | --- |"]
            for row in installed:
                detail = row["reason"] or "; ".join(row["evidence"][:8])
                lines.append("| %s / %s | %s | %s | %s |" % (row["qt"], row["variant"], row["operation"],
                                                             row["status"], detail.replace("|", "/")))
        reasons = [r for r in matrix if r["status"] != "passed"]
        if reasons:
            lines += ["", "## Reasons", ""]
            for row in reasons:
                lines.append("- **%s / %s / %s — %s: %s.** %s" % (row["qt"], row["variant"], row["configuration"],
                                                                 row["operation"], row["status"],
                                                                 row["reason"].replace("\n", " ")))
        lines += ["", "## Evidence per passed check", ""]
        for row in matrix:
            if row["status"] == "passed":
                lines.append("- %s / %s / %s — %s: %s" % (row["qt"], row["variant"], row["configuration"],
                                                          row["operation"], "; ".join(row["evidence"])))
        return "\n".join(lines) + "\n"

    def write(self, extra_dirs=()):
        os.makedirs(self.out_dir, exist_ok=True)
        paths = []
        for directory in (self.out_dir,) + tuple(extra_dirs):
            json_path = os.path.join(directory, "WP-088-results.json" if directory != self.out_dir else "results.json")
            md_path = os.path.join(directory, "WP-088-results.md" if directory != self.out_dir else "results.md")
            with open(json_path, "w") as out:
                json.dump(self.document(), out, indent=2)
                out.write("\n")
            with open(md_path, "w") as out:
                out.write(self.markdown())
            paths += [json_path, md_path]
        return paths
